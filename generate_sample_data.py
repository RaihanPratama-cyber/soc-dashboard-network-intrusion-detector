"""Generate data/sample_attacks.csv — a small, labelled, simulated dataset.

The numbers mirror Raihan's WKJ lab observations (reduced to a demo-sized
excerpt so the file stays small):

* MAC flooding (macof): 54-byte frames, many random source MACs on one port.
* DHCP starvation (yersinia): a burst of DHCP DISCOVER packets to port 68,
  each with its own Transaction ID — the real lab saw 3,306,566 DISCOVERs
  and Transaction ID 0x643c9869.
* ARP poisoning (Cain & Abel / hping3): IP 10.10.1.11 claimed by two MACs,
  conflicting with 10.10.1.13.
* Port scan: one host probing many destination ports.

Plus a stretch of normal background traffic so the dashboard is not 100%
attack traffic. This file is SIMULATED — generated by this script, not a
real packet capture — and is labelled in the ``label`` column.
"""

import csv
import random
from datetime import datetime, timedelta

OUT = "data/sample_attacks.csv"
random.seed(42)

BASE = datetime(2026, 11, 12, 10, 0, 0)
ATTACKER_MAC = "aa:bb:cc:11:22:33"
VICTIM_MAC = "00:1a:2b:3c:4d:5e"      # 10.10.1.11 (legit)
GATEWAY_MAC = "00:1a:2b:3c:4d:5f"     # 10.10.1.13 (gateway)
SWITCH_PORT = "Fa0/1"

rows = []


def add(ts, src_mac, dst_mac, src_ip, dst_ip, src_port, dst_port,
        protocol, frame_len, info, label, port=""):
    rows.append({
        "timestamp": ts.strftime("%Y-%m-%dT%H:%M:%S"),
        "src_mac": src_mac, "dst_mac": dst_mac,
        "src_ip": src_ip, "dst_ip": dst_ip,
        "src_port": src_port, "dst_port": dst_port,
        "protocol": protocol, "frame_len": frame_len,
        "info": info, "label": label, "port": port,
    })


def rand_mac():
    return ":".join(f"{random.randint(0, 255):02x}" for _ in range(6))


# --- Normal background traffic: 10:00–10:02 -------------------------------
for i in range(40):
    ts = BASE + timedelta(seconds=i * 3)
    add(ts, VICTIM_MAC, GATEWAY_MAC, "10.10.1.11", "10.10.1.13",
        49152 + i, 443, "TCP", 120 + i % 200,
        "TLS Application Data", "normal", SWITCH_PORT)

# --- MAC flooding (macof), 10:02:00–10:02:50: 60 random MACs, 54-byte frames
for i in range(60):
    ts = BASE + timedelta(minutes=2, seconds=i)
    add(ts, rand_mac(), "ff:ff:ff:ff:ff:ff", "0.0.0.0", "255.255.255.255",
        0, 0, "Ethernet", 54, "macof forged frame, 54 bytes", "mac_flooding",
        SWITCH_PORT)

# --- DHCP starvation (yersinia), 10:03:00–10:03:59: 120 DISCOVERs ----------
for i in range(120):
    ts = BASE + timedelta(minutes=3, seconds=i // 2)
    txid = f"0x{0x643c9869 + i:08x}" if i == 0 else f"0x{random.randint(0, 0xffffffff):08x}"
    add(ts, rand_mac(), "ff:ff:ff:ff:ff:ff", "0.0.0.0", "255.255.255.255",
        68, 67, "DHCP", 342,
        f"DHCP Discover - Transaction ID {txid}", "dhcp_starvation", SWITCH_PORT)

# --- ARP poisoning (Cain & Abel / hping3), 10:04 ---------------------------
for i in range(12):
    ts = BASE + timedelta(minutes=4, seconds=i * 5)
    # Attacker answers ARP for 10.10.1.11 with its own MAC.
    add(ts, ATTACKER_MAC, "ff:ff:ff:ff:ff:ff", "10.10.1.11", "10.10.1.13",
        0, 0, "ARP", 42,
        "Who has 10.10.1.11? Tell 10.10.1.13 (gratuitous ARP reply)",
        "arp_poisoning", SWITCH_PORT)
# Legitimate replies for the same IP, so the conflict is visible.
for i in range(4):
    ts = BASE + timedelta(minutes=4, seconds=i * 12)
    add(ts, VICTIM_MAC, "ff:ff:ff:ff:ff:ff", "10.10.1.11", "10.10.1.13",
        0, 0, "ARP", 42, "Who has 10.10.1.11? Tell 10.10.1.13",
        "normal", SWITCH_PORT)

# --- Port scan, 10:05:00–10:05:40: one host, 20 ports ----------------------
for i, dport in enumerate([21, 22, 23, 25, 53, 80, 110, 135, 139, 143, 443,
                           445, 993, 995, 1723, 3306, 3389, 5432, 5900, 8080]):
    ts = BASE + timedelta(minutes=5, seconds=i * 2)
    add(ts, ATTACKER_MAC, GATEWAY_MAC, "10.10.1.99", "10.10.1.13",
        40000 + i, dport, "TCP", 60, f"TCP SYN to port {dport}",
        "port_scan", SWITCH_PORT)

# --- Normal traffic again, 10:06 ------------------------------------------
for i in range(20):
    ts = BASE + timedelta(minutes=6, seconds=i * 3)
    add(ts, VICTIM_MAC, GATEWAY_MAC, "10.10.1.11", "8.8.8.8",
        49152 + i, 53, "UDP", 78, "Standard query A", "normal", SWITCH_PORT)

rows.sort(key=lambda r: r["timestamp"])

with open(OUT, "w", newline="", encoding="utf-8") as fh:
    writer = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
    writer.writeheader()
    writer.writerows(rows)

print(f"Wrote {len(rows)} rows to {OUT}")
